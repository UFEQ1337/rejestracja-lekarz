-- Schemat bazy danych systemu rejestracji do lekarza

CREATE TABLE specialization (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT uk_specialization_name UNIQUE (name)
);

CREATE TABLE doctor (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name     VARCHAR(60)  NOT NULL,
    last_name      VARCHAR(80)  NOT NULL,
    license_number VARCHAR(7)   NOT NULL,
    email          VARCHAR(120) NOT NULL,
    phone          VARCHAR(20),
    room           VARCHAR(10),
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_doctor_license UNIQUE (license_number),
    CONSTRAINT uk_doctor_email UNIQUE (email)
);
CREATE INDEX idx_doctor_last_name ON doctor (last_name);

-- relacja N:M lekarz - specjalizacja
CREATE TABLE doctor_specialization (
    doctor_id         BIGINT NOT NULL,
    specialization_id BIGINT NOT NULL,
    CONSTRAINT pk_doctor_specialization PRIMARY KEY (doctor_id, specialization_id),
    CONSTRAINT fk_ds_doctor FOREIGN KEY (doctor_id) REFERENCES doctor (id) ON DELETE CASCADE,
    CONSTRAINT fk_ds_specialization FOREIGN KEY (specialization_id) REFERENCES specialization (id)
);
CREATE INDEX idx_ds_specialization ON doctor_specialization (specialization_id);

CREATE TABLE patient (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(60)  NOT NULL,
    last_name  VARCHAR(80)  NOT NULL,
    pesel      VARCHAR(11)  NOT NULL,
    email      VARCHAR(120) NOT NULL,
    phone      VARCHAR(20),
    birth_date DATE,
    CONSTRAINT uk_patient_pesel UNIQUE (pesel),
    CONSTRAINT uk_patient_email UNIQUE (email)
);
CREATE INDEX idx_patient_last_name ON patient (last_name);

-- relacja 1:N lekarz - terminy
CREATE TABLE time_slot (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id  BIGINT    NOT NULL,
    start_time TIMESTAMP NOT NULL,
    end_time   TIMESTAMP NOT NULL,
    booked     BOOLEAN   NOT NULL DEFAULT FALSE,
    version    BIGINT    NOT NULL DEFAULT 0,
    CONSTRAINT fk_slot_doctor FOREIGN KEY (doctor_id) REFERENCES doctor (id),
    CONSTRAINT uk_slot_doctor_start UNIQUE (doctor_id, start_time),
    CONSTRAINT ck_slot_time CHECK (end_time > start_time)
);
CREATE INDEX idx_slot_start_time ON time_slot (start_time);

-- relacje 1:N pacjent - wizyty oraz termin - wizyty (historia anulowanych)
CREATE TABLE appointment (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id      BIGINT      NOT NULL,
    patient_id   BIGINT      NOT NULL,
    status       VARCHAR(20) NOT NULL,
    reason       VARCHAR(500),
    created_at   TIMESTAMP   NOT NULL,
    cancelled_at TIMESTAMP,
    CONSTRAINT fk_appointment_slot FOREIGN KEY (slot_id) REFERENCES time_slot (id),
    CONSTRAINT fk_appointment_patient FOREIGN KEY (patient_id) REFERENCES patient (id),
    CONSTRAINT ck_appointment_status CHECK (status IN ('BOOKED', 'CANCELLED', 'COMPLETED'))
);
CREATE INDEX idx_appointment_patient ON appointment (patient_id);
CREATE INDEX idx_appointment_slot ON appointment (slot_id);
CREATE INDEX idx_appointment_status ON appointment (status);

-- konta uzytkownikow (pacjent, rejestratorka, lekarz)
CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    patient_id    BIGINT,
    doctor_id     BIGINT,
    CONSTRAINT uk_user_username UNIQUE (username),
    CONSTRAINT uk_user_patient UNIQUE (patient_id),
    CONSTRAINT uk_user_doctor UNIQUE (doctor_id),
    CONSTRAINT fk_user_patient FOREIGN KEY (patient_id) REFERENCES patient (id),
    CONSTRAINT fk_user_doctor FOREIGN KEY (doctor_id) REFERENCES doctor (id),
    CONSTRAINT ck_user_role CHECK (role IN ('PATIENT', 'RECEPTIONIST', 'DOCTOR'))
);
